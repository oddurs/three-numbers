/**
 * Rendering figures to disk.
 *
 * Each figure becomes one self-contained SVG (rasters embedded as data URIs) at
 * exactly its final printed size in points, so that text inside a figure is set
 * at the same optical size as the text around it. A manifest is emitted
 * alongside for Typst to read captions and dimensions from.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { paths } from "../paths.ts";
import { serialize } from "../draw/svg.ts";
import { figureWidthPt, type FigureDefinition } from "../figures/define.ts";
import { loadFigures, type LoadedFigure } from "../figures/registry.ts";

export interface RenderedFigure {
  readonly id: string;
  readonly file: string;
  readonly bytes: number;
  readonly widthPt: number;
  readonly heightPt: number;
  readonly ms: number;
  readonly changed: boolean;
}

const escapeTypst = (s: string): string => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

/** Write only if the bytes differ, so Typst's watcher stays quiet. */
export function writeIfChanged(file: string, content: string): boolean {
  try {
    if (readFileSync(file, "utf8") === content) return false;
  } catch {
    /* not present yet */
  }
  writeFileSync(file, content);
  return true;
}

export async function renderFigures(
  only?: readonly string[],
): Promise<{ rendered: RenderedFigure[]; figures: FigureDefinition[] }> {
  mkdirSync(paths.buildFigures, { recursive: true });
  const loaded: LoadedFigure[] = await loadFigures();
  const selected = only?.length ? loaded.filter((f) => only.includes(f.def.id)) : loaded;

  const rendered: RenderedFigure[] = [];
  for (const { def } of selected) {
    const started = performance.now();
    const doc = def.render();
    const svg = serialize(doc);
    const file = join(paths.buildFigures, `${def.id}.svg`);
    const changed = writeIfChanged(file, svg);
    rendered.push({
      id: def.id,
      file,
      bytes: Buffer.byteLength(svg),
      widthPt: doc.width,
      heightPt: doc.height,
      ms: performance.now() - started,
      changed,
    });
  }

  writeManifest(loaded.map((l) => l.def));
  return { rendered, figures: loaded.map((l) => l.def) };
}

/**
 * The Typst-side manifest: a dictionary of figure metadata that `#fig()` reads,
 * so captions live with the code that draws the figure rather than in the prose.
 */
export function writeManifest(figures: FigureDefinition[]): void {
  mkdirSync(paths.buildFigures, { recursive: true });

  const entries = [...figures]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((f) => {
      const width = figureWidthPt(f);
      const sources = (f.sources ?? []).map((s) => `"${s}"`).join(", ");
      return [
        `  "${f.id}": (`,
        `    title: "${escapeTypst(f.title)}",`,
        `    caption: [${f.caption}],`,
        `    chapter: "${f.chapter}",`,
        `    placement: "${f.placement ?? "column"}",`,
        `    width: ${width.toFixed(2)}pt,`,
        `    path: "${f.id}.svg",`,
        `    sources: (${sources}${(f.sources?.length ?? 0) === 1 ? "," : ""}),`,
        `  ),`,
      ].join("\n");
    });

  const typ = [
    "// Generated by `node engine/cli.ts figures` -- do not edit.",
    "#let figures = (",
    ...entries,
    ")",
    "",
  ].join("\n");
  writeIfChanged(join(paths.buildFigures, "manifest.typ"), typ);

  const json = JSON.stringify(
    figures.map((f) => ({
      id: f.id,
      title: f.title,
      chapter: f.chapter,
      placement: f.placement ?? "column",
      width: figureWidthPt(f),
      sources: f.sources ?? [],
      claim: f.claim ?? null,
    })),
    null,
    2,
  );
  writeIfChanged(join(paths.buildFigures, "manifest.json"), `${json}\n`);
}
