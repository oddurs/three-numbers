/**
 * Version stamping.
 *
 * A draft of a book circulates. Six months later someone quotes a figure number
 * from a PDF nobody can identify. So every build stamps what it is — the
 * version, the commit it came from, whether the tree was clean, and the date —
 * into the colophon, and a release refuses to proceed from a dirty tree.
 */

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { paths } from "../paths.ts";
import { writeIfChanged } from "./figures.ts";

export interface VersionInfo {
  /** From package.json. */
  readonly version: string;
  /** Nearest tag, or `null` outside a tagged history. */
  readonly tag: string | null;
  readonly commit: string | null;
  readonly shortCommit: string | null;
  readonly branch: string | null;
  /** True when the working tree has uncommitted changes. */
  readonly dirty: boolean;
  /** ISO date of the build. */
  readonly date: string;
  /** True when this build sits exactly on a tag and the tree is clean. */
  readonly released: boolean;
}

const git = (...args: string[]): string | null => {
  const res = spawnSync("git", args, { cwd: paths.root, encoding: "utf8" });
  if (res.status !== 0) return null;
  const out = res.stdout.trim();
  return out === "" ? null : out;
};

export function versionInfo(): VersionInfo {
  let version = "0.0.0";
  try {
    version = JSON.parse(readFileSync(join(paths.root, "package.json"), "utf8")).version ?? version;
  } catch { /* keep the default */ }

  const commit = git("rev-parse", "HEAD");
  const tag = git("describe", "--tags", "--exact-match");
  const dirty = git("status", "--porcelain") !== null;

  return {
    version,
    tag,
    commit,
    shortCommit: commit ? commit.slice(0, 8) : null,
    branch: git("rev-parse", "--abbrev-ref", "HEAD"),
    dirty,
    date: new Date().toISOString().slice(0, 10),
    released: tag !== null && !dirty,
  };
}

/** A one-line human description, for the colophon and the terminal. */
export function describe(v: VersionInfo): string {
  if (v.released) return `version ${v.tag}`;
  const bits = [`version ${v.version}`, "draft"];
  if (v.shortCommit) bits.push(v.shortCommit + (v.dirty ? "+" : ""));
  return bits.join(" · ");
}

/** Write `build/version.typ` for the colophon to include. */
export function writeVersion(): VersionInfo {
  const v = versionInfo();
  mkdirSync(paths.build, { recursive: true });
  const q = (s: string | null) => (s === null ? "none" : JSON.stringify(s));
  const typ = [
    "// Generated by the build -- do not edit.",
    "#let build-info = (",
    `  version: ${q(v.version)},`,
    `  tag: ${q(v.tag)},`,
    `  commit: ${q(v.shortCommit)},`,
    `  branch: ${q(v.branch)},`,
    `  dirty: ${v.dirty},`,
    `  date: ${q(v.date)},`,
    `  released: ${v.released},`,
    `  describe: ${JSON.stringify(describe(v))},`,
    ")",
    "",
  ].join("\n");
  writeIfChanged(join(paths.build, "version.typ"), typ);
  return v;
}
